"""Contracts consumed by application services; no host or network imports."""
from typing import Protocol

from .models import FileAsset, MediaUnit, TorrentSnapshot


class TaskStore(Protocol):
    def read(self) -> dict: ...
    def write(self, state: dict) -> None: ...


class DownloaderPort(Protocol):
    def associate(self, unit: MediaUnit, files: list[FileAsset]) -> list[TorrentSnapshot]: ...
    def mark_retained(self, torrent: TorrentSnapshot) -> None: ...
    def cleanup(self, job: dict, checkpoint) -> dict: ...
    def deletion_allowed(self, files: list[FileAsset]) -> bool: ...


class RemuxPort(Protocol):
    def submit(self, request: dict) -> str: ...
    def status(self, job_id: str) -> dict: ...


class CloudStoragePort(Protocol):
    def find(self, asset: FileAsset, directory: str, name: str) -> dict | None: ...
    def upload(self, asset: FileAsset, directory: str, name: str) -> dict: ...
    def verify(self, asset: FileAsset, receipt: dict) -> None: ...


class StrmPort(Protocol):
    def publish(self, job: dict) -> list[dict]: ...
    def verify(self, artifacts: list[dict]) -> None: ...


class MediaLibraryPort(Protocol):
    def discover(self, users: list[str], *, unit_keys: list[str] | None = None, resolve_episodes: bool = True) -> list[MediaUnit]: ...
    def capture_states(self, unit: MediaUnit, users: list[str]) -> dict: ...
    def migrate(self, job: dict, artifacts: list[dict], checkpoint) -> None: ...
    def verify_migration(self, job: dict, artifacts: list[dict]) -> None: ...


class FilesPort(Protocol):
    def capture(self, paths: list[str]) -> list[FileAsset]: ...
    def verify(self, files: list[FileAsset]) -> None: ...
    def is_disc(self, path: str) -> bool: ...
    def validate_output(self, source: str, directory: str) -> None: ...
    def describe(self, files: list[FileAsset]) -> list[FileAsset]: ...
    def inspect_media(self, path: str) -> dict: ...
    def commit_outputs(self, job: dict, outputs: list[dict]) -> list[dict]: ...
    def remove(self, files: list[FileAsset]) -> None: ...


class DiscEnginePort(Protocol):
    def inspect(self, source: str) -> list[dict]: ...
    def convert(self, job: dict, progress) -> list[dict]: ...
